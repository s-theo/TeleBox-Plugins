// 获取命令前缀
const prefixes = getPrefixes()
const mainPrefix = prefixes[0] || '.'
const shortCommandName = `${mainPrefix}ss`

const getErrorMessage = (error: unknown): string => {
  if (error instanceof Error) return error.message
  if (typeof error === 'string') return error
  if (error && typeof error === 'object' && 'message' in error && typeof error.message === 'string') {
    return error.message
  }
  return String(error)
}

const getTelegramError = (error: unknown): string | undefined => {
  if (error && typeof error === 'object' && 'errorMessage' in error && typeof error.errorMessage === 'string') {
    return error.errorMessage
  }
  return undefined
}

// HTML转义
const htmlEscape = (text: string): string =>
  text.replace(
    /[&<>"']/g,
    (m) =>
      ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#x27;'
      })[m] || m
  )

const isImageDocument = (document: Api.Document): boolean => {
  if ((document.mimeType || '').startsWith('image/')) return true
  const fileName = document.attributes?.find((attr) => attr instanceof Api.DocumentAttributeFilename)?.fileName || ''
  return /\.(?:jpe?g|png|webp|gif|bmp|tiff?|avif|heic|heif)$/i.test(fileName)
}

